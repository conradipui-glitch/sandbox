export function russia1917CampaignBeatForTurn(turn: number): CampaignBeat {
  const safeTurn = Math.max(1, turn);
  const act = campaignActForTurn(safeTurn);
  const actStarts = [1, 8, 17, 27];
  const start = actStarts[act.number - 1] ?? 1;
  const offsetsByAct = [
    Math.min(2, Math.floor((safeTurn - start) / 3)),
    Math.min(1, Math.floor((safeTurn - start) / 5)),
    Math.min(1, Math.floor((safeTurn - start) / 5)),
    1,
  ];
  const indexByAct = [0, 3, 5, 7];
  const index = Math.min(russia1917CampaignBeats.length - 1, (indexByAct[act.number - 1] ?? 0) + (offsetsByAct[act.number - 1] ?? 0));
  return russia1917CampaignBeats[index];
}
