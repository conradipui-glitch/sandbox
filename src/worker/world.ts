const characterById = new Map(worldCharacters.map((character) => [character.id, character]));

export function campaignAct(turn: number): string {
  if (turn <= 7) return "I. Март–апрель: легитимность и двоевластие";
  if (turn <= 16) return "II. Май–июль: война, земля и хлеб";
  if (turn <= 26) return "III. Август–октябрь: переворот и радикализация";
  return "IV. После ноября: новая форма государства";
}

function weakestMetric(state: GameState): MetricId {
  return [...state.metrics].sort((a, b) => a.value - b.value)[0]?.id ?? "stability";
}

export function worldContextForTurn(state: GameState, action: string) {
  const weak = weakestMetric(state);
  const ids = new Set(["minister-levitsky"]);
  if (/арм|фронт|мир|солдат/i.test(action) || weak === "army") ids.add("colonel-argunov");
  if (/газет|телеграф|утеч|авто|публич|лидия|ветров/i.test(action) || weak === "diplomacy") ids.add("lidia-vetrova");
  if (/рабоч|хлеб|забаст/i.test(action) || weak === "economy") ids.add("worker-novikova");
  if (/земл|крестьян|деревн/i.test(action)) ids.add("peasant-grushina");
  if (/банк|завод|кредит|промыш/i.test(action)) ids.add("industrialist-vorontsova");
  if (/поезд|вагон|угол|снабж/i.test(action)) ids.add("rail-belyaev");
  if (/автоном|федерац|регион|язык/i.test(action)) ids.add("regional-iskander");
  const cast = [...ids].slice(0, 4).map((id) => characterById.get(id));

  return {
    mode: gameModes[state.mode],
    act: state.mode === "campaign" ? campaignAct(state.turn) : gameModes[state.mode].title,
    weakestMetric: weak,
    cast,
    entityPool: worldEntities.filter((entity) =>
      weak === "economy" ? ["bread-cards", "freight-train", "yard-horse", "factory-yard"].includes(entity.id) :
      weak === "army" ? ["field-telephone", "armored-car", "freight-train", "station-crows"].includes(entity.id) :
      ["coded-telegram", "staff-renault", "tauride-garden", "samovar"].includes(entity.id),
    ),
    microEncounters: microEncounters.slice(0, state.turn % 2 === 0 ? 3 : 2),
    contract: [
      "Персонаж знает только то, что мог узнать; он может ошибаться, лгать, отказываться и помнить прежнее обращение игрока.",
      "Событие обязано иметь материальную причину, исполнителя, задержку и цену.",
      "Юмор редкий и наблюдательный; бедность, насилие и уязвимые люди не являются шуткой.",
      "Не более двух заметных анимационных действий в одной сцене.",
    ],
  };
}
